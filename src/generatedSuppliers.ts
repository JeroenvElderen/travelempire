import {meters,type Point,type RoadGraph} from './simulation/taxi';
import type {CollectorPart} from './resourceCollectors';

export type SupplierReservation={quantity:number;pickupAt:number};
export type GeneratedSupplier={id:string;name:string;position:Point;node:string;part:CollectorPart;capacity:number;stock:number;updatedAt:number;reservations?:SupplierReservation[];size:'Small'|'Medium'|'Large'|'Industrial'};
export const SUPPLIER_COLORS:Record<CollectorPart,string>={mechanical:'#dc2626',business:'#2563eb',construction:'#d97706',electronics:'#9333ea',research:'#0891b2',energy:'#16a34a',marine:'#0284c7',rare:'#db2777'};
const weights:readonly [CollectorPart,number][]=[['mechanical',25],['business',20],['construction',15],['electronics',12],['research',10],['energy',8],['marine',7],['rare',3]];
const names:Record<CollectorPart,string>={mechanical:'Mechanical supply',business:'Business supply',construction:'Building materials',electronics:'Electronics supply',research:'Research supplies',energy:'Energy supply',marine:'Marine supply',rare:'Specialist components'};
const hour=3600000;
export const SUPPLIER_PRODUCTION_HOURS:Readonly<Record<CollectorPart,number>>={mechanical:1,business:1,construction:1.5,electronics:2,research:3,energy:4,marine:5,rare:8};
export const SUPPLIER_BATCH_UNITS=2;
const productionInterval=(supplier:GeneratedSupplier)=>SUPPLIER_PRODUCTION_HOURS[supplier.part]*hour;
function hash(input:string):number{
 let h=2166136261;
 for(let i=0;i<input.length;i++)h=Math.imul(h^input.charCodeAt(i),16777619);
 return h>>>0;
}
function randomPart(seed:string,coastal:boolean,urban:boolean,industrial:boolean):CollectorPart{
 const weighted=weights.map(([part,n])=>[part,n*(part==='marine'?(coastal?2.5:.35):part==='business'&&urban?1.6:part==='construction'&&industrial?1.5:1)] as const);
 let roll=(hash(seed+':part')/4294967296)*weighted.reduce((sum,x)=>sum+x[1],0);
 for(const [part,n] of weighted){roll-=n;if(roll<0)return part;}
 return 'mechanical';
}
/** Evaluate completed pickups in chronological order, applying production
 * before each pickup. Reserved cargo stays physically at the supplier until
 * loading finishes. The original production phase is preserved. */
function supplierSnapshot(supplier:GeneratedSupplier,now:number):GeneratedSupplier{
 let stock=supplier.stock,updatedAt=supplier.updatedAt;
 const interval=productionInterval(supplier);
 const advance=(at:number)=>{
  const cycles=Math.max(0,Math.floor((at-updatedAt)/interval));
  stock=Math.min(supplier.capacity,stock+cycles*SUPPLIER_BATCH_UNITS);
  updatedAt+=cycles*interval;
 };
 const reservations=[...(supplier.reservations??[])].sort((a,b)=>a.pickupAt-b.pickupAt);
 const pending:SupplierReservation[]=[];
 for(const reservation of reservations){
  if(reservation.pickupAt>now){pending.push(reservation);continue;}
  advance(reservation.pickupAt);
  stock=Math.max(0,stock-reservation.quantity);
 }
 advance(now);
 return {...supplier,stock,updatedAt,reservations:pending.length?pending:undefined};
}
export function supplierStock(supplier:GeneratedSupplier,now:number):number{
 return supplierSnapshot(supplier,now).stock;
}
export function supplierReserved(supplier:GeneratedSupplier,now:number):number{
 return (supplier.reservations??[]).reduce((n,r)=>n+(r.pickupAt>now?r.quantity:0),0);
}
export function supplierAvailable(supplier:GeneratedSupplier,now:number):number{
 return Math.max(0,supplierStock(supplier,now)-supplierReserved(supplier,now));
}
export function supplierVisible(supplier:GeneratedSupplier,now:number):boolean{return supplierStock(supplier,now)>0;}
/** Immediate withdrawals remain supported for old callers. A future pickup
 * reserves available inventory without physically removing it. */
export function reserveSupplier(supplier:GeneratedSupplier,now:number,wanted:number,pickupAt=now):{supplier:GeneratedSupplier;quantity:number}{
 const snapshot=supplierSnapshot(supplier,now);
 const quantity=Math.max(0,Math.min(snapshot.stock-supplierReserved(snapshot,now),Math.floor(wanted)));
 if(!quantity)return {supplier:snapshot,quantity:0};
 if(pickupAt<=now)return {quantity,supplier:{...snapshot,stock:snapshot.stock-quantity}};
 const reservations=[...(snapshot.reservations??[]),{quantity,pickupAt}].sort((a,b)=>a.pickupAt-b.pickupAt);
 return {quantity,supplier:{...snapshot,reservations}};
}
/** One persistent seeded supplier per roughly 300m cell, at an actual discovered
 * non-restricted road node. No supplier is generated by simply viewing a road. */
export function generateSuppliers(existing:Record<string,GeneratedSupplier>,graph:RoadGraph,discovered:Set<string>,nodes:readonly string[],seed:string,now:number,coasts:readonly Point[]=[],cities:readonly Point[]=[]):Record<string,GeneratedSupplier>{
 let result=existing;
 for(const node of nodes){
  const position=graph.nodes.get(node);if(!position)continue;
  const edges=graph.edges.get(node)??[];
  const edge=edges.find(e=>!e.taxiOnly&&discovered.has(e.id));if(!edge)continue;
  const cell=Math.floor(position[0]/.004)+':'+Math.floor(position[1]/.004);
  const id='supply:'+cell;if(result[id])continue;
  const key=seed+':'+cell;
  const coastal=coasts.some(p=>meters(position,p)<6000),urban=cities.some(p=>meters(position,p)<5000);
  const part=randomPart(key,coastal,urban,/primary|secondary|industrial/.test(edge.highway??''));
  const roll=hash(key+':size')%100;
  const size=roll<55?'Small':roll<85?'Medium':roll<97?'Large':'Industrial';
  const bounds=size==='Small'?[50,150]:size==='Medium'?[150,400]:size==='Large'?[400,1000]:[1000,3000];
  const capacity=bounds[0]+hash(key+':capacity')%(bounds[1]-bounds[0]+1);
  if(result===existing)result={...existing};
  result[id]={id,name:size+' '+names[part],position:[...position],node,part,size,capacity,stock:0,updatedAt:now};
 }
 return result;
}
